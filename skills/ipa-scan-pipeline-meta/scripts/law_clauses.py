THIRD_PARTY_ONLY_CLAUSES = {
    "工信部337号文 · 第四项",             # App 公示第三方 SDK 收集规则
    "《App违法违规收集使用个人信息行为认定方法》 · 第2条（三）",  # 未逐一列出第三方 SDK
    "安卓应用商店上架审核要求（各商店通用条款） · SDK 披露项",    # SDK 目录披露
    "GB/T 35273《个人信息安全规范》 · 9.7",  # 委托处理/接入第三方 SDK 的评估披露义务
}

def get_laws(rtag, party="first"):
    """按 R 维度取条款，party=first 时剔除三方专属条款（QC 复核用）"""
    dims = [d.strip() for d in re.split(r'[·/，,]', rtag or '') if d.strip().startswith('R')]
    if not dims:
        dims = ['R1']
    out = []
    for d in dims:
        for item in LAWS.get(d, []):
            key = item['law'] + ' · ' + item['clause']
            if party == "first" and key in THIRD_PARTY_ONLY_CLAUSES:
                continue
            out.append(item)
    return out
